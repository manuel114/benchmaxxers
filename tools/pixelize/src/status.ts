import { existsSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { ASSETS, type AssetDef } from '@benchmaxxers/shared/assets';
import { REPO_ROOT } from './palette.js';

/** Where finished images live. */
const ASSET_DIR = join(REPO_ROOT, 'assets');

/** Batch titles, matching art/CODEX.md. */
const BATCHES: Record<number, string> = {
  1: 'Style tile',
  2: 'Toned agent (character reference)',
  3: 'Other builds: Noodle, Buff, Maxxed',
  4: 'Floors and walls',
  5: 'Props and machines',
  6: 'On-machine animations',
  7: 'Waiting and celebrating',
  8: 'Effects and UI',
  9: 'Front-desk staff and brand',
};

/** True when the asset's image file exists. */
const present = (a: AssetDef): boolean => existsSync(join(ASSET_DIR, a.file));

/** Writes the manifest the game reads. */
const writeManifest = (): void => {
  const game = ASSETS.filter((a) => !a.file.startsWith('..'));
  const manifest = {
    note: 'Generated by `pnpm assets:status` from packages/shared/src/assets.ts. Do not edit by hand.',
    assets: Object.fromEntries(game.map((a) => [a.id, {
      file: a.file, width: a.width, height: a.height, frames: a.frames, fps: a.fps ?? 0,
      anchor: a.anchor, palette: a.palette, phase: a.phase, present: present(a),
    }])),
  };
  mkdirSync(ASSET_DIR, { recursive: true });
  writeFileSync(join(ASSET_DIR, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
};

/** Writes the human checklist, grouped by batch. */
const writeChecklist = (): { done: number; total: number } => {
  const v1 = ASSETS.filter((a) => a.phase === 'v1');
  const done = v1.filter(present).length;
  const lines: string[] = [
    '# Asset list',
    '',
    'Generated by `pnpm assets:status` from [`packages/shared/src/assets.ts`](../packages/shared/src/assets.ts). Edit that file, not this one. How to make each batch: [`CODEX.md`](CODEX.md). Style rules: [`STYLE.md`](STYLE.md).',
    '',
    `**First version: ${done} of ${v1.length} done.**`,
    '',
    'Sizes are in art pixels. Animations are one row of frames, left to right.',
    '',
  ];
  for (const [batch, title] of Object.entries(BATCHES)) {
    const items = ASSETS.filter((a) => a.batch === Number(batch));
    lines.push(`## Batch ${batch}: ${title}`, '', '| Done | Id | File | Frame size | Frames | Palette | Draw |', '| --- | --- | --- | --- | --- | --- | --- |');
    for (const a of items) {
      const mark = present(a) ? '✅' : a.phase === 'later' ? 'later' : '⬜';
      const file = a.file.startsWith('..') ? a.file.replace('../', '') : `assets/${a.file}`;
      lines.push(`| ${mark} | \`${a.id}\` | \`${file}\` | ${a.width}×${a.height} | ${a.frames}${a.fps ? ` @ ${a.fps}/s` : ''} | ${a.palette} | ${a.brief} |`);
    }
    lines.push('');
  }
  writeFileSync(join(REPO_ROOT, 'art', 'ASSETS.md'), lines.join('\n'));
  return { done, total: v1.length };
};

writeManifest();
const { done, total } = writeChecklist();
console.log(`First version assets: ${done} of ${total} done. Updated art/ASSETS.md and assets/manifest.json.`);
